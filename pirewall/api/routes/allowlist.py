"""`GET/POST/DELETE /api/v1/allowlist` (ADDENDUM.md A2, PLAN_FINAL §4.9).

An allowlist entry outranks every adaptive rule, so adding one is treated
as the most sensitive write the API offers: it needs the admin password
again (counted by the login throttle when wrong), it names one device only,
and it is announced as a WARNING event.
"""

from datetime import UTC, datetime
from typing import Any

from fastapi import APIRouter, HTTPException, Request

from pirewall.api.app import AuthenticatorDep, LoginThrottleDep, RpcClientDep, SessionDep
from pirewall.api.schemas import AllowlistCreateRequest, MessageResponse
from pirewall.api.throttle import record_failed_authentication, refuse_if_locked_out
from pirewall.core.enums import EventSeverity, SecurityEventType
from pirewall.core.models.allowlist import AllowlistEntry
from pirewall.core.models.event import SecurityEvent

router = APIRouter(prefix="/api/v1/allowlist", tags=["allowlist"])


@router.get("", response_model=list[AllowlistEntry])
def list_allowlist(rpc_client: RpcClientDep) -> list[AllowlistEntry]:
    return rpc_client.list_allowlist()


@router.post("")
def add_allowlist_entry(
    body: AllowlistCreateRequest,
    request: Request,
    rpc_client: RpcClientDep,
    session: SessionDep,
    authenticator: AuthenticatorDep,
    throttle: LoginThrottleDep,
) -> dict[str, Any]:
    """Add an allowlist entry, optionally provisioning a portal account with it.

    Refused with 429 while the login throttle is locked, and 403 when the
    password is wrong (a failed login for the throttle). An optional `mac`
    pins the entry to that device (ADDENDUM_4.md D3): core then refuses any
    adaptive rule against that IP *or* that MAC, and writes the pair to the
    kernel's `allow_bound` sets on the v2 path.

    Returns the entry as JSON, plus `portal_username`/`portal_password` when
    one was provisioned (ADDENDUM_3.md C3). The password is generated by
    pirewall-core, returned here exactly once, and never stored in readable
    form — so this response is the only chance to record it.

    Not declared with `response_model=AllowlistEntry`: that would strip the
    two portal fields off the response, silently discarding the only copy of
    a password an admin was told they would be shown.
    """
    now = datetime.now(UTC)
    client_host = request.client.host if request.client else None
    refuse_if_locked_out(throttle, client_host, now)
    if not authenticator.confirm_password(body.password.get_secret_value()):
        record_failed_authentication(
            throttle,
            rpc_client,
            client_host,
            now,
            f"password re-confirmation failed for an allowlist addition by {session.username!r}",
        )
        raise HTTPException(status_code=403, detail="password confirmation failed")
    entry = AllowlistEntry(
        target=body.target,
        port=body.port,
        protocol=body.protocol,
        reason=body.reason,
        created_at=now,
        created_by=session.username,
        mac=body.mac,
    )
    created = rpc_client.add_allowlist_entry_with_portal_user(entry, body.portal_username)
    scope = "" if body.port is None else f" port {body.port}"
    device = "" if entry.mac is None else f" ({entry.mac})"
    rpc_client.record_event(
        SecurityEvent(
            timestamp=now,
            severity=EventSeverity.WARNING,
            event_type=SecurityEventType.FIREWALL_ALLOW,
            subsystem="api.allowlist",
            reason=(
                f"allowlist entry added for {entry.target}{device}{scope} by {session.username!r}: "
                f"{entry.reason} (exempt from every adaptive rule)"
            ),
        )
    )
    return created


@router.delete("/{entry_id}", response_model=MessageResponse)
def remove_allowlist_entry(entry_id: str, rpc_client: RpcClientDep) -> MessageResponse:
    removed = rpc_client.remove_allowlist_entry(entry_id)
    if not removed:
        raise HTTPException(status_code=404, detail="allowlist entry not found")
    return MessageResponse(message="removed")
